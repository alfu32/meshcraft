"""Index names/types from the unmodified, vendored official IFC4X3_ADD2 schema."""
import json
import re
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

root = Path(__file__).resolve().parents[2]
source = root / 'vendor/ifc4.3.2.0'
entries = []
with zipfile.ZipFile(source / 'annex-a-psd.zip') as archive:
    for filename in sorted(archive.namelist()):
        node = ET.fromstring(archive.read(filename))
        set_name = node.findtext('Name')
        for p in node.findall('./PropertyDefs/PropertyDef'):
            t = p.find('PropertyType')
            spec = list(t)[0]
            tag = spec.tag
            kind = {'TypePropertySingleValue':'single', 'TypePropertyEnumeratedValue':'enumerated',
                    'TypePropertyListValue':'list','TypePropertyBoundedValue':'bounded',
                    'TypePropertyTableValue':'table','TypePropertyReferenceValue':'reference'}.get(tag, 'complex')
            dt = spec.find('.//DataType')
            dtype = dt.get('type') if dt is not None else spec.get('reftype', 'IfcLabel')
            secondary=spec.find('./DefinedValue/DataType')
            choices = [v.text for v in spec.findall('.//EnumItem')]
            entries.append({'set':set_name,'name':p.findtext('Name'),'kind':kind,'dataType':dtype,'choices':choices,'secondaryDataType':secondary.get('type') if secondary is not None else None})
        for p in node.findall('./QtoDefs/QtoDef'):
            entries.append({'set':set_name,'name':p.findtext('Name'),'kind':'quantity',
                'dataType':p.findtext('QtoType'),'choices':[]})
exp = (source / 'IFC4X3_ADD2.exp').read_text()
definitions = dict(re.findall(r'^TYPE\s+(\w+)\s*=\s*(.*?);', exp, re.M | re.S))
types=sorted(definitions)
def primitive(name,seen=()):
    if name in seen:return 'SELECT'
    base=definitions.get(name,name).strip().split()[0].split('(')[0]
    return primitive(base,seen+(name,)) if base in definitions else base
kinds={name:primitive(name) for name in types}
def value_types(name):
    definition=definitions.get(name,'')
    if definition.startswith('SELECT'):
        result=set()
        for child in re.findall(r'\bIfc\w+',definition):result.update(value_types(child))
        return result
    return {name}
values=sorted(value_types('IfcValue'))
(source / 'catalog.json').write_text(json.dumps({'schema':'IFC4X3_ADD2','version':'4.3.2.0','types':types,'typeKinds':kinds,'valueTypes':values,'properties':entries},separators=(',',':'))+'\n')
print(len(entries), 'properties;',len(types),'types')

# Searchable human-readable companions to the exact runtime catalog.
import csv
import io
from collections import defaultdict

groups = defaultdict(list)
for entry in entries:
    groups[entry['set']].append(entry)
lines = [
    '# IFC 4.3.2.0 properties and quantities', '',
    f'Complete official PSD catalog: **{len(entries):,} entries in {len(groups)} sets**.', '',
    'This lists property/quantity definitions, rather than the attributes of every IFC entity.',
    'Custom property sets can also be defined. See the [editing guide](ifc-properties.md)',
    'and [CSV catalog](ifc4-properties.csv).', '',
    'Source: [buildingSMART IFC4X3_ADD2](https://standards.buildingsmart.org/IFC/RELEASE/IFC4_3/).',
    'Generated by `python3 scripts/ifc/catalog.py` from the pinned official archive.', '',
]
output = io.StringIO(newline='')
writer = csv.writer(output, lineterminator="\n")
writer.writerow(['set', 'property', 'kind', 'data_type', 'secondary_data_type', 'allowed_values'])
for set_name, properties in sorted(groups.items()):
    lines.extend([f'## {set_name}', '', '| Property | Kind | IFC type | Allowed values |', '| --- | --- | --- | --- |'])
    for entry in sorted(properties, key=lambda p: p['name']):
        data_type = entry['dataType']
        if entry.get('secondaryDataType'):
            data_type += ' → ' + entry['secondaryDataType']
        choices = ', '.join(entry['choices'])
        lines.append(f"| {entry['name']} | {entry['kind']} | {data_type} | {choices.replace('|', '&#124;')} |")
        writer.writerow([set_name, entry['name'], entry['kind'], entry['dataType'], entry.get('secondaryDataType') or '', choices])
    lines.append('')
(root / 'docs/ifc4-properties.md').write_text('\n'.join(lines))
(root / 'docs/ifc4-properties.csv').write_text(output.getvalue(), newline='')
print(len(groups), 'sets; Markdown and CSV lists generated')
